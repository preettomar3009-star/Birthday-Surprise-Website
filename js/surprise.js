const sorryGrid = document.getElementById("sorryGrid");
const messageCount = document.getElementById("messageCount");

sorryMessages.forEach((message, index) => {
  const card = document.createElement("div");
  card.className = "sorry-card";

  const number = document.createElement("span");
  number.className = "card-number";
  number.textContent = `SORRY ${index + 1}`;

  const text = document.createElement("p");
  text.className = "card-message";
  text.textContent = message;

  card.appendChild(number);
  card.appendChild(text);
  sorryGrid.appendChild(card);
});

messageCount.textContent = sorryMessages.length;

// Floating hearts animation
const heartsContainer = document.getElementById("floatingHearts");

function createFloatingHeart() {
  const heart = document.createElement("span");
  heart.className = "floating-heart";
  heart.textContent = Math.random() > 0.5 ? "♡" : "♥";
  heart.style.left = Math.random() * 100 + "%";
  heart.style.fontSize = (18 + Math.random() * 20) + "px";

  const duration = 5 + Math.random() * 5;
  heart.style.animationDuration = duration + "s";

  heartsContainer.appendChild(heart);

  setTimeout(() => heart.remove(), duration * 1000);
}

setInterval(createFloatingHeart, 550);